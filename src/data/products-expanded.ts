export const products = [...baseProducts, ...extraProducts];

export function getProduct(id: string): Product | undefined {
  return products.find((product) => product.id === id);
}

export function getProductsByCategory(category: Product["category"]): Product[] {
  return products.filter((product) => product.category === category);
}

export function getFeaturedProducts(limit = 12): Product[] {
  const featured = products.filter((product) => product.featured);
  if (featured.length >= limit) return featured.slice(0, limit);
  const others = products.filter((product) => !product.featured);
  return [...featured, ...others].slice(0, limit);
}

export function getDeals(limit = 12): Product[] {
  const deals = products.filter((product) => typeof product.compareAt === "number");
  if (deals.length >= limit) return deals.slice(0, limit);
  return products.slice(0, limit);
}

export function discountOf(product: Product): number {
  if (typeof product.compareAt !== "number" || product.compareAt <= product.price) return 0;
  return Math.round(((product.compareAt - product.price) / product.compareAt) * 100);
}

export function formatUnit(product: Product): string {
  if (product.unit === "kg" && product.size === 1) return "kg";
  if (product.unit === "g") return `${product.size} g`;
  if (product.unit === "ml") return `${product.size} ml`;
  if (product.unit === "L" && product.size === 1) return "L";
  if (product.unit === "dz") return `${product.size} dz`;
  if (product.unit === "cx") return `${product.size} cx`;
  if (product.unit === "pct") return `${product.size} pct`;
  return `${product.size} ${product.unit}`;
}
